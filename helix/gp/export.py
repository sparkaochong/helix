def render_apply_script(
    library: FactorLibrary,
    ic_targets: list[str],
    date_column: str = "trade_date",
    code_column: str = "stock_code",
    search_end: str = "",
) -> str:
    """Build the standalone script source for ``library``."""
    if library.kind != "event":
        raise ValueError(f"apply-script export is for event libraries, got {library.kind!r}")

    try:
        assert_no_label_columns(library.field_names)
    except AssertionError as exc:
        raise ValueError(str(exc)) from exc
    invalid = [n for n in library.field_names if not n.isidentifier()]
    if invalid:
        raise ValueError(
            f"these column names are not valid Python identifiers and cannot appear in an "
            f"evaluated expression: {invalid}"
        )

    factor_names = [factor.name for factor in library.factors]
    invalid_factor_names = [
        name
        for name in factor_names
        if type(name) is not str or not name.isidentifier()
    ]
    if invalid_factor_names:
        raise ValueError(f"invalid factor output name: {invalid_factor_names}")
    duplicate_factor_names = sorted(
        {name for name in factor_names if factor_names.count(name) > 1}
    )
    if duplicate_factor_names:
        raise ValueError(f"duplicate factor output name: {duplicate_factor_names}")
    reserved_names = {
        date_column,
        code_column,
        *library.field_names,
        *ic_targets,
        *GP_FACTOR_AUDIT_COLUMNS,
    }
    colliding_factor_names = sorted(
        name
        for name in factor_names
        if name in reserved_names or is_label_column(name)
    )
    if colliding_factor_names:
        raise ValueError(
            "factor output name collides with retained/reserved columns: "
            f"{colliding_factor_names}"
        )

    factors = [
        {"name": f.name, "expression": f.expression, "sign": f.sign} for f in library.factors
    ]
    return _TEMPLATE.format(
        n_factors=len(factors),
        date_column=date_column,
        code_column=code_column,
        search_end=search_end,
        field_names=json.dumps(library.field_names, indent=4),
        factors_json=json.dumps(factors, ensure_ascii=False),
        ic_targets=json.dumps(ic_targets),
        label_prefixes_json=json.dumps(LABEL_PREFIXES),
        gp_source_date=GP_FACTOR_AUDIT_COLUMNS[0],
        gp_as_of_time=GP_FACTOR_AUDIT_COLUMNS[1],
        gp_price_basis=GP_FACTOR_AUDIT_COLUMNS[2],
        gp_adj_factor_version=GP_FACTOR_AUDIT_COLUMNS[3],
    )


def write_apply_script(
    path: Path, library: FactorLibrary, ic_targets: list[str], search_end: str = ""
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_apply_script(library, ic_targets, search_end=search_end), encoding="utf-8"
    )
    path.chmod(0o755)
    log.info("wrote standalone apply script for %d factors to %s", len(library.factors), path)
    return path
